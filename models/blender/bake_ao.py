"""Bake the cars' ambient occlusion into the models already in models/ (no rebuild, so every shape stays exactly as it is):

    blender -b --factory-startup --python models/blender/bake_ao.py -- --car gr86,gt3rs      (or --car all)

Each models/<id>.glb is imported, carkit.bake_ao_scene() bakes its '_AO' (the body with its wheels and a road under it,
the wheels and calipers on their own), and models/<id>.glb + <id>.glb.js are written again with the same Draco settings
(the .js keeps its "Generated by" line). A model that already has '_AO' is skipped unless --force. New exports from the
car scripts bake it themselves (carkit.main; --no-ao skips it)."""
import bpy, os, sys, json, struct
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import carkit

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
arg = lambda n, d=None: argv[argv.index(n) + 1] if n in argv else d


def has_ao(glb):
    with open(glb, 'rb') as f: b = f.read()
    n = struct.unpack('<I', b[12:16])[0]; j = json.loads(b[20:20 + n])
    return any('_AO' in p['attributes'] for m in j.get('meshes', []) for p in m['primitives'])


def car_ids():
    """every car model in models/: a 'Body' node and 'Wheel_*' nodes (the traffic models, tr_*, stay without: the game
    merges them per material)"""
    out = []
    for f in sorted(os.listdir(os.path.join(REPO, 'models'))):
        if not f.endswith('.glb') or f.startswith('tr_'): continue
        with open(os.path.join(REPO, 'models', f), 'rb') as h: b = h.read()
        n = struct.unpack('<I', b[12:16])[0]; names = [x.get('name', '') for x in json.loads(b[20:20 + n]).get('nodes', [])]
        if 'Body' in names and any(x.startswith('Wheel_') for x in names): out.append(f[:-4])
    return out


ids = car_ids() if arg('--car', 'all') == 'all' else arg('--car').split(',')
for cid in ids:
    glb = os.path.join(REPO, 'models', cid + '.glb')
    if not os.path.exists(glb): print('no model', cid, flush=True); continue
    if has_ao(glb) and '--force' not in argv: print('already baked', cid, flush=True); continue
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.gltf(filepath=glb)
    scene = bpy.context.scene
    tris0 = sum(len(p.vertices) - 2 for o in scene.objects if o.type == 'MESH' for p in o.data.polygons)
    carkit.bake_ao_scene(scene)
    bpy.ops.object.select_all(action='SELECT')
    with open(glb + '.js') as f: header = f.readline()
    if not header.startswith('//'): header = f'// Generated by models/blender/bake_ao.py from {cid}.glb - do not edit.\n'
    size0 = os.path.getsize(glb)
    carkit.write_glb(glb, header)
    print(f'baked {cid}: {tris0} triangles, {size0 / 1e3:.0f} -> {os.path.getsize(glb) / 1e3:.0f} kB', flush=True)
